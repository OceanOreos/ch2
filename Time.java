public class Time{
	
	public static void main (String[] args) {
		
		// Declaring and assigning variables 
		int hour;
	    hour = 14;
	    int minutes;
	    minutes = 40;
	    
	    // Concatenate
	    System.out.println("This is the seconds since midnight: " + (hour * 3600 + minutes * 60) + ".");
	    System.out.print("It is currently 2:40 pm" + ".");
	    
	}
}
